/**
 * מיפוי מהווידאו (864×496) למסך: הווידאו ממלא את המסך בלי עיוות (יחס נשמר), והחיתוך בעיקר מלמטה (רצפת הקרח)
 * כדי שהראש והקרניים לא ייחתכו. אותו מיפוי משמש לציור הווידאו ולבדיקת הפגיעה.
 */
object BossFrame {
    const val VIDEO_W = 864f
    const val VIDEO_H = 496f
    const val VIDEO_ASPECT = VIDEO_W / VIDEO_H

    /** איזה חלק מהעודף האנכי נחתך מלמעלה (0 = רק מלמטה, 0.5 = שווה) */
    const val ANCHOR_Y = 0.2f

    /**
     * [שמאל, למעלה, רוחב, גובה] של הווידאו המוצג, בשברי מסך (יכול לחרוג מ-0..1, החריגה נחתכת).
     * aspect = רוחב/גובה של המסך.
     */
    fun rect(aspect: Float): FloatArray =
        if (aspect >= VIDEO_ASPECT) {
            val h = aspect / VIDEO_ASPECT
            floatArrayOf(0f, -(h - 1f) * ANCHOR_Y, 1f, h)
        } else {
            val w = VIDEO_ASPECT / aspect
            floatArrayOf(-(w - 1f) / 2f, 0f, w, 1f)
        }

    fun screenX(vx: Float, r: FloatArray): Float = r[0] + vx / VIDEO_W * r[2]
    fun screenY(vy: Float, r: FloatArray): Float = r[1] + vy / VIDEO_H * r[3]

    /** אורך בפיקסלי וידאו, בשברי גובה מסך */
    fun screenLen(px: Float, r: FloatArray): Float = px / VIDEO_H * r[3]
}
