    /**
     * מיקומי הנקודות בזמן ms בסרטון (פיקסלים של הווידאו), עם אינטרפולציה בין דגימות.
     * out: [x0, y0, r0, x1, y1, r1, ...]. מחזיר false אם אין מעקב לסרטון.
     */
    fun points(clip: BossClip, ms: Float, out: FloatArray): Boolean {
        val t = table(clip) ?: return false
        val samples = t.size / (POINTS * 2)
        val f = (ms / 1000f * FPS / STEP_FRAMES).coerceIn(0f, (samples - 1).toFloat())
        val i0 = f.toInt().coerceIn(0, samples - 1)
        val i1 = (i0 + 1).coerceAtMost(samples - 1)
        val k = f - i0
        for (p in 0 until POINTS) {
            val a = (i0 * POINTS + p) * 2
            val b = (i1 * POINTS + p) * 2
            out[p * 3] = t[a] + (t[b] - t[a]) * k
            out[p * 3 + 1] = t[a + 1] + (t[b + 1] - t[a + 1]) * k
        }
        val dx = out[3] - out[6]
        val dy = out[4] - out[7]
        val scale = (kotlin.math.sqrt(dx * dx + dy * dy) / BASE_SHOULDERS).coerceIn(0.8f, 1.5f)
        for (p in 0 until POINTS) out[p * 3 + 2] = BASE_RADIUS[p] * scale
        return true
    }
