    /** טבלת המעקב של הסרטון, או null אם בסרטון הזה הבוס לא פגיע (כניסה, מוות) */
    /** מעקב של בוס של עולם אחר (BossWorld): טבלה לכל קטע, רדיוסים, ומרחק הכתפיים בעמידה. null = בוס הקרח */
    class Custom(val tables: Map<BossClip, IntArray>, val radius: FloatArray?, val shoulders: Float)

    @Volatile
    var custom: Custom? = null

    fun table(clip: BossClip): IntArray? = custom?.let { return it.tables[clip] } ?: builtIn(clip)

    private fun builtIn(clip: BossClip): IntArray? = when (clip) {
        BossClip.Breath -> BREATH
        BossClip.Prepare -> PREPARE
        BossClip.Attack1 -> ATTACK1
        BossClip.Attack3 -> ATTACK3
        BossClip.Attack4 -> ATTACK4
        BossClip.Attack5 -> ATTACK5
        BossClip.HitHead -> HIT_HEAD
        BossClip.HitRightShoulder -> HIT_RSHOULDER
        BossClip.HitLeftShoulder -> HIT_LSHOULDER
        BossClip.HitRightHand -> HIT_RHAND
        BossClip.HitLeftHand -> HIT_LHAND
        else -> null
    }

    /** האם יש מעקב אמין בזמן ms (במתקפות: רק עד רגע לפני שהבוס זז מהר מדי) */
    fun covers(clip: BossClip, ms: Float): Boolean {
        val t = table(clip) ?: return false
        val samples = t.size / (POINTS * 2)
        return ms / 1000f * FPS / STEP_FRAMES <= samples - 1 + 0.5f
    }

    /**
     * מיקומי הנקודות בזמן ms בסרטון (פיקסלים של הווידאו), עם אינטרפולציה בין דגימות.
     * out: [x0, y0, r0, x1, y1, r1, ...]. מחזיר false אם אין מעקב לסרטון.
     */
    fun points(clip: BossClip, ms: Float, out: FloatArray): Boolean {
        val t = table(clip) ?: return false
        if (!clip.loop && clip != BossClip.Breath && clip != BossClip.Prepare && !covers(clip, ms)) return false
        val samples = t.size / (POINTS * 2)
        val f = (ms / 1000f * FPS / STEP_FRAMES).coerceIn(0f, (samples - 1).toFloat())
        val i0 = f.toInt().coerceIn(0, samples - 1)
        val i1 = (i0 + 1).coerceAtMost(samples - 1)
        val k = f - i0
        for (p in 0 until POINTS) {
            val a = (i0 * POINTS + p) * 2
            val b = (i1 * POINTS + p) * 2
            out[p * 3] = t[a] + (t[b] - t[a]) * k
            out[p * 3 + 1] = t[a + 1] + (t[b + 1] - t[a + 1]) * k
        }
        val dx = out[3] - out[6]
        val dy = out[4] - out[7]
        val cu = custom
        val baseShoulders = cu?.shoulders?.takeIf { it > 0f } ?: BASE_SHOULDERS
        val radius = cu?.radius?.takeIf { it.size >= POINTS } ?: BASE_RADIUS
        val scale = (kotlin.math.sqrt(dx * dx + dy * dy) / baseShoulders).coerceIn(0.8f, 1.5f)
        for (p in 0 until POINTS) out[p * 3 + 2] = radius[p] * scale
        return true
    }
}

/**
 * מיפוי מהווידאו (864×496) למסך: הווידאו ממלא את המסך בלי עיוות (יחס נשמר), והחיתוך בעיקר מלמטה (רצפת הקרח)
 * כדי שהראש והקרניים לא ייחתכו. אותו מיפוי משמש לציור הווידאו ולבדיקת הפגיעה.
 */
object BossFrame {
    const val VIDEO_W = 864f
    const val VIDEO_H = 496f
    const val VIDEO_ASPECT = VIDEO_W / VIDEO_H

    /** איזה חלק מהעודף האנכי נחתך מלמעלה (0 = רק מלמטה, 0.5 = שווה) */
    const val ANCHOR_Y = 0.2f

    /**
     * [שמאל, למעלה, רוחב, גובה] של הווידאו המוצג, בשברי מסך (יכול לחרוג מ-0..1, החריגה נחתכת).
     * aspect = רוחב/גובה של המסך.
     */
    fun rect(aspect: Float): FloatArray =
        if (aspect >= VIDEO_ASPECT) {
            val h = aspect / VIDEO_ASPECT
            floatArrayOf(0f, -(h - 1f) * ANCHOR_Y, 1f, h)
        } else {
            val w = VIDEO_ASPECT / aspect
            floatArrayOf(-(w - 1f) / 2f, 0f, w, 1f)
        }

    fun screenX(vx: Float, r: FloatArray): Float = r[0] + vx / VIDEO_W * r[2]
    fun screenY(vy: Float, r: FloatArray): Float = r[1] + vy / VIDEO_H * r[3]

    /** אורך בפיקסלי וידאו, בשברי גובה מסך */
    fun screenLen(px: Float, r: FloatArray): Float = px / VIDEO_H * r[3]

    /** נקודה בשברי וידאו (0..1) אל שברי מסך */
    fun fracToScreenX(fx: Float, r: FloatArray): Float = r[0] + fx * r[2]
    fun fracToScreenY(fy: Float, r: FloatArray): Float = r[1] + fy * r[3]
}
